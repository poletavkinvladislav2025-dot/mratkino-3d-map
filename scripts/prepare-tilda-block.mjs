/** Reuse the owner's ordinary-map card UI with the SAME data as the existing 3D map. */
import fs from 'node:fs';
import {PLACES} from '../src/region/presets.js';
import {placeKind} from '../src/region/card-content.js';
const legacyId=p=>p.sourceRecord?.sourceId||p.id;
const byId=new Map(PLACES.map(p=>[p.id,p]));
const catalog=PLACES.map(p=>({id:legacyId(p),canonicalId:p.id,kind:p.kind,name:p.name,type:placeKind(p.kind),desc:p.description||'',coords:[p.coordinates[1],p.coordinates[0]],zoom:p.kind==='stamp-point'?16:15,url:p.sourceRecord?.url||p.url||'',photos:(p.photos?.length?p.photos:p.photo?[{url:p.photo,alt:p.name}]:[]).map(p=>({src:p.url,alt:p.alt||''})),...(p.kind==='stamp-point'?{sellsPassports:p.sellsPassport===true,isStampFree:p.sellsPassport===false,passportInfo:p.conditions||'',stamps:p.stamps.map(s=>({name:s.name,...(s.placeId&&byId.has(s.placeId)?{locationId:legacyId(byId.get(s.placeId))}:{})}))}:{} )}));
fs.writeFileSync('public/integration/map-catalog.json',JSON.stringify(catalog,null,2)+'\n');
const markup=fs.readFileSync('src/integration/yandex-template.html','utf8');
const adapter=fs.readFileSync('docs/snippets/yandex-adapter.js','utf8');
const runtime=fs.readFileSync('src/integration/yandex-runtime.js','utf8').replace('/* @YandexAdapter */',adapter);
const output=`/* Generated by scripts/prepare-tilda-block.mjs; do not edit. */
(function(){
'use strict';
const script=document.currentScript,config=script.dataset,base=new URL('.',script.src);
if(document.querySelector('.vb-t1')||document.getElementById('vb-map-modes')){const warning=document.createElement('p');warning.textContent='Удалите прежний блок обычной карты и прежний переключатель. Оставьте один новый блок карты и опубликуйте страницу.';warning.setAttribute('role','alert');script.before(warning);return;}
const holder=document.createElement('div');holder.className='vb-map-complete';holder.innerHTML=${JSON.stringify(markup)};script.before(holder);
${runtime}
// Catalog is generated from PLACES, including the corrected tower and both Malinovaya IDs.
mountYandex(${JSON.stringify(catalog)},config);
const loader=document.createElement('script');loader.src=new URL('tilda-map-switch.js?v=20261027-filters',base).href;loader.dataset.defaultMode=config.defaultMode||'3d';loader.dataset.mapUrl=new URL('../?v=20261027-filters',base).href;holder.after(loader);
})();
`;
fs.writeFileSync('public/integration/tilda-map-block.js',output);
console.log(`Shared Tilda block: ${catalog.length} places/points, ${Buffer.byteLength(output)} bytes hosted outside Tilda`);
